#!/usr/bin/env bash
set -euo pipefail

# Deploy script for the vf-materials-bot platform. Runs ON THE SERVER as root:
# GitHub Actions executes `sudo deploy/deploy.sh`, deploy_user has NOPASSWD for it.
#
# Pipeline:
#   1. git pull --ff-only
#   2. sync server infrastructure FROM the repository (source of truth):
#      - deploy/*.service        -> /etc/systemd/system/ (+ enable, daemon-reload)
#      - /etc/sudoers.d/vf-materials-bot-deploy (regenerated, visudo-checked)
#      - /etc/nginx/.htpasswd-api-docs (basic auth docs API, из API_DOCS_USER/API_DOCS_PASSWORD в .env)
#      - deploy/nginx-mybot.conf -> /etc/nginx/sites-available/mybots (+ nginx -t, reload,
#        old config backed up to /etc/vf-materials-backup)
#   3. uv sync
#   4. alembic upgrade head (один раз, до рестартов всех сервисов)
#   5. restart services enabled by .env flags + health-check
#
# Server-side edits of units/sudoers/nginx are overwritten on every deploy.
# Change them in the repository instead — ручных правок на сервере не требуется.

# Каталог репозитория берём из расположения скрипта, а не хардкодом: так деплой
# не зависит от абсолютного пути (каталог на сервере — /opt/vashfindir).
WORK_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SYSTEMD_DIR="/etc/systemd/system"
SUDOERS_FILE="/etc/sudoers.d/vf-materials-bot-deploy"
NGINX_SRC="deploy/nginx-mybot.conf"
NGINX_AVAIL="/etc/nginx/sites-available/mybots"
NGINX_ENABL="/etc/nginx/sites-enabled/mybots"
BACKUP_DIR="/etc/vf-materials-backup"

SERVICE_NAME="vf-materials-bot"
ADMIN_SERVICE_NAME="vf-materials-bot-admin"
API_SERVICE_NAME="vf-materials-api"
WORKER_SERVICE_NAME="vf-materials-worker"

# sudo сбрасывает PATH до secure_path, где нет uv: добавляем известные места установки.
export PATH="$PATH:/home/deploy_user/.local/bin:$HOME/.local/bin"

log() {
    echo "[$(date +'%Y-%m-%d %H:%M:%S')] $*"
}

if [[ "${1:-}" == "--help" || "${1:-}" == "-h" ]]; then
    cat <<EOF
Usage: $0

Deploys the latest master to production:
  1. git pull --ff-only origin <current branch>
  2. syncs systemd units, sudoers and nginx config from the repository
  3. uv sync
  4. alembic upgrade head
  5. systemctl restart (per flags in .env):
     - vf-materials-bot                     (always)
     - vf-materials-bot-admin               (ADMIN_SECRET_KEY)
     - vf-materials-api                     (API_TOKEN or LEAD_API_TOKEN)
     - vf-materials-worker                  (WORKER_ENABLED=true)

Requires:
  - repository cloned to $WORK_DIR
  - .env configured in $WORK_DIR
  - run as root (via NOPASSWD sudo for deploy_user)

.env is NEVER updated by this script. Update it manually via:
  deploy/update-env.sh
EOF
    exit 0
fi

if [[ ! -d "$WORK_DIR" ]]; then
    log "ERROR: project directory $WORK_DIR does not exist"
    exit 1
fi

cd "$WORK_DIR"

if [[ ! -f ".env" ]]; then
    log "ERROR: .env not found in $WORK_DIR"
    log "Copy it manually: deploy/update-env.sh"
    exit 1
fi

log "Pulling latest changes..."
head_before="$(git rev-parse HEAD)"
git pull --ff-only origin "$(git branch --show-current)"
if [[ "$(git rev-parse HEAD)" != "$head_before" ]]; then
    # Код обновился — продолжаем деплой скриптом из новой ревизии. Иначе bash
    # продолжил бы выполнять уже перезаписанный git pull'ом старый файл.
    log "Code updated, re-running deploy from the new revision..."
    exec bash "$0" "$@"
fi

# --- Инфраструктура из репозитория -------------------------------------------------

log "Syncing systemd units from repository..."
units_changed=0
for unit in deploy/*.service; do
    name="$(basename "$unit")"
    if ! cmp -s "$unit" "$SYSTEMD_DIR/$name"; then
        cp "$unit" "$SYSTEMD_DIR/$name"
        units_changed=1
        log "Updated unit $name"
    fi
    systemctl enable "$SYSTEMD_DIR/$name" >/dev/null
done
if [[ "$units_changed" -eq 1 ]]; then
    systemctl daemon-reload
    log "systemd daemon-reload done"
fi

log "Syncing sudoers from repository..."
sudoers_tmp="$(mktemp)"
{
    echo "# Generated by deploy/deploy.sh from repository state."
    echo "# Server-side edits are overwritten on every deploy."
    for unit in deploy/*.service; do
        name="$(basename "$unit" .service)"
        echo "deploy_user ALL=(ALL) NOPASSWD: /bin/systemctl restart $name"
        echo "deploy_user ALL=(ALL) NOPASSWD: /bin/systemctl status $name"
        echo "deploy_user ALL=(ALL) NOPASSWD: /bin/systemctl is-active $name"
    done
    echo "deploy_user ALL=(ALL) NOPASSWD: /usr/bin/journalctl"
    echo "deploy_user ALL=(ALL) NOPASSWD: $WORK_DIR/deploy/deploy.sh"
    # Параллельная запись для старого каталога — убрать после того, как переезд
    # /opt/vf_materials_bot → /opt/vashfindir состоится на всех серверах.
    echo "deploy_user ALL=(ALL) NOPASSWD: /opt/vf_materials_bot/deploy/deploy.sh"
} > "$sudoers_tmp"
chmod 440 "$sudoers_tmp"
visudo -cf "$sudoers_tmp" >/dev/null
cp "$sudoers_tmp" "$SUDOERS_FILE"
rm -f "$sudoers_tmp"

log "Generating API docs htpasswd for nginx basic auth..."
# nginx-mybot.conf ссылается на этот файл (auth_basic_user_file), поэтому он должен
# существовать до nginx -t. Креды берём из .env; если не заданы — пишем случайную
# пару: конфиг валиден, но docs закрыты для всех.
API_DOCS_HTPASSWD="/etc/nginx/.htpasswd-api-docs"
API_DOCS_USER="$(sed -n 's/^API_DOCS_USER=//p' .env | tail -n 1)"
API_DOCS_PASSWORD="$(sed -n 's/^API_DOCS_PASSWORD=//p' .env | tail -n 1)"
if [[ -z "$API_DOCS_USER" || -z "$API_DOCS_PASSWORD" ]]; then
    log "WARNING: API_DOCS_USER/API_DOCS_PASSWORD not set in .env, API docs closed for everyone"
    API_DOCS_USER="disabled"
    API_DOCS_PASSWORD="$(openssl rand -hex 24)"
fi
printf '%s:%s\n' "$API_DOCS_USER" "$(openssl passwd -apr1 "$API_DOCS_PASSWORD")" > "$API_DOCS_HTPASSWD"
chmod 640 "$API_DOCS_HTPASSWD"
chown root:www-data "$API_DOCS_HTPASSWD" 2>/dev/null || true

log "Syncing nginx site config from repository..."
if [[ -f "$NGINX_AVAIL" ]] && ! cmp -s "$NGINX_SRC" "$NGINX_AVAIL"; then
    mkdir -p "$BACKUP_DIR"
    cp "$NGINX_AVAIL" "$BACKUP_DIR/mybots.$(date +%Y%m%d%H%M%S).conf"
    cp "$NGINX_SRC" "$NGINX_AVAIL"
    ln -sfn ../sites-available/mybots "$NGINX_ENABL"
    nginx -t
    systemctl reload nginx
    log "nginx config updated; old version backed up to $BACKUP_DIR"
elif [[ ! -f "$NGINX_AVAIL" ]]; then
    cp "$NGINX_SRC" "$NGINX_AVAIL"
    ln -sfn ../sites-available/mybots "$NGINX_ENABL"
    nginx -t
    systemctl reload nginx
    log "nginx config installed"
fi

# --- Код и данные ------------------------------------------------------------------

log "Syncing dependencies..."
# После переезда каталога (/opt/vf_materials_bot → /opt/vashfindir) shebang-скрипты
# .venv/bin/* ссылаются на старый абсолютный путь. Проверяем на примере alembic:
# сломано — пересобираем окружение целиком (деплой идёт от root, venv принадлежит root).
if ! "$WORK_DIR/.venv/bin/alembic" --version &>/dev/null; then
    log "Broken venv scripts detected (directory relocation), full reinstall..."
    uv sync --reinstall
else
    uv sync
fi

log "Applying migrations..."
uv run alembic upgrade head

SERVICES=("$SERVICE_NAME")
if grep -qE '^ADMIN_SECRET_KEY=.+' .env; then
    SERVICES+=("$ADMIN_SERVICE_NAME")
else
    log "WARNING: ADMIN_SECRET_KEY is not set in .env, skipping $ADMIN_SERVICE_NAME"
fi

if grep -qE '^(API_TOKEN|LEAD_API_TOKEN)=.+' .env; then
    SERVICES+=("$API_SERVICE_NAME")
else
    log "WARNING: neither API_TOKEN nor LEAD_API_TOKEN is set in .env, skipping $API_SERVICE_NAME"
fi

if grep -qE '^WORKER_ENABLED=true' .env; then
    SERVICES+=("$WORKER_SERVICE_NAME")
else
    log "WARNING: WORKER_ENABLED is not set to true in .env, skipping $WORKER_SERVICE_NAME"
fi

# Сервис без установленного юнита пропускаем (деплой только что синкнул все юниты,
# сюда попадаем лишь при нештатных ручных правках на сервере).
INSTALLED_SERVICES=()
for service in "${SERVICES[@]}"; do
    if systemctl cat "$service" &>/dev/null; then
        INSTALLED_SERVICES+=("$service")
    else
        log "WARNING: unit $service is not installed on this server, skipping"
        log "         It is installed automatically from deploy/ on the next deploy"
    fi
done
SERVICES=("${INSTALLED_SERVICES[@]}")

for service in "${SERVICES[@]}"; do
    log "Restarting service $service..."
    sudo -n systemctl restart "$service"
done

log "Waiting for services to start..."
sleep 2

for service in "${SERVICES[@]}"; do
    if sudo -n systemctl is-active --quiet "$service"; then
        log "SUCCESS: $service is active"
    else
        log "ERROR: $service failed to start"
        sudo -n systemctl is-active "$service" || true
        exit 1
    fi
done
